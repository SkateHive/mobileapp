// Signs Android release builds with the Play upload key, and fails closed without it.
//
// The key and its passwords never enter the repo. They live in a properties file outside it, by default
// ~/.skatehive/android-upload.properties, or wherever SKATEHIVE_UPLOAD_PROPERTIES points (a relative path
// is relative to the repo root):
//
//   storeFile=skatehive-upload.keystore        (relative to this file, or absolute)
//   storePassword=...
//   keyAlias=upload
//   keyPassword=...
//   uploadCertSha256=AA:BB:...                  (checked by scripts/build-android-aab.js)
//
// Debug builds never need it. A release build (assemble/bundle/package/sign *Release) without a valid
// config FAILS, instead of silently signing with the debug key. For a local release build meant only for
// test phones, set SKATEHIVE_ALLOW_DEBUG_RELEASE=1 to sign it with the debug key on purpose (an incomplete
// or unreadable config still fails). The Play bundle is built with `pnpm build:android:aab`, which never
// sets that flag and verifies the bundle's signer.
//
// android/ is generated by prebuild, so this edits app/build.gradle there.
const { withAppBuildGradle } = require("expo/config-plugins");

const MARK = "// skatehive-release-signing";

const HELPER = `${MARK}: the Play upload key lives outside the repo.
// Returns [props: Properties] for a valid config, [error: String] for a broken one, or [absent: File].
def skatehiveUploadSigning() {
    def path = System.getenv('SKATEHIVE_UPLOAD_PROPERTIES') ?: "\${System.getProperty('user.home')}/.skatehive/android-upload.properties"
    def f = new File(path)
    if (!f.isAbsolute()) f = new File(rootDir.parentFile, path)
    if (!f.exists()) return [absent: f]
    if (!f.canRead()) return [error: "Upload key config \${f} is not readable."]
    def p = new Properties()
    f.withInputStream { p.load(it) }
    def missing = ['storeFile', 'storePassword', 'keyAlias', 'keyPassword'].findAll { !p[it] }
    if (missing) return [error: "Upload key config \${f} is missing: \${missing.join(', ')}."]
    def store = new File(p['storeFile'])
    if (!store.isAbsolute()) store = new File(f.parentFile, p['storeFile'])
    if (!store.canRead()) return [error: "The keystore \${store} named in \${f} is not readable."]
    p['storeFile'] = store.absolutePath
    return [props: p]
}
`;

const GUARD = `
${MARK}: a release build without a valid upload key config fails instead of signing with the debug key.
gradle.taskGraph.whenReady { graph ->
    def isRelease = graph.allTasks.any { t ->
        t.project == project && t.name ==~ /(assemble|bundle|package|sign)(.*)Release(.*)/
    }
    if (!isRelease) return
    def s = skatehiveUploadSigning()
    if (s.props) return
    if (s.error) throw new GradleException(s.error)
    if (System.getenv('SKATEHIVE_ALLOW_DEBUG_RELEASE') == '1') {
        logger.warn("SkateHive: release build signed with the DEBUG key (SKATEHIVE_ALLOW_DEBUG_RELEASE=1). Not for Play.")
        return
    }
    throw new GradleException("No Play upload key config at \${s.absent}. Set it up (see plugins/withAndroidReleaseSigning.js), " +
        "or set SKATEHIVE_ALLOW_DEBUG_RELEASE=1 for a local test build signed with the debug key.")
}
`;

module.exports = function withAndroidReleaseSigning(config) {
  return withAppBuildGradle(config, (c) => {
    let gradle = c.modResults.contents;
    if (gradle.includes(MARK)) return c;

    const steps = [
      [/\nandroid \{/, `\n${HELPER}\nandroid {`],
      [
        /signingConfigs \{\n(\s+)debug \{/,
        (_m, ind) =>
          `signingConfigs {\n${ind}release {\n${ind}    def s = skatehiveUploadSigning()\n` +
          `${ind}    if (s.props) {\n` +
          `${ind}        storeFile file(s.props['storeFile'])\n` +
          `${ind}        storePassword s.props['storePassword']\n` +
          `${ind}        keyAlias s.props['keyAlias']\n` +
          `${ind}        keyPassword s.props['keyPassword']\n` +
          `${ind}    }\n${ind}}\n${ind}debug {`,
      ],
      [
        /(release \{\n(?:\s*\/\/[^\n]*\n)*\s*)signingConfig signingConfigs\.debug/,
        "$1signingConfig skatehiveUploadSigning().props ? signingConfigs.release : signingConfigs.debug",
      ],
    ];
    for (const [pattern, replacement] of steps) {
      if (!pattern.test(gradle)) {
        throw new Error(`withAndroidReleaseSigning: app/build.gradle no longer matches ${pattern}`);
      }
      gradle = gradle.replace(pattern, replacement);
    }
    c.modResults.contents = gradle + GUARD;
    return c;
  });
};
